using System.Globalization;
using System.Text;

namespace Flowamaz.Application.Workflow.Interpreter;

/// <summary>
/// Renders a narrative (the small Markdown subset the Interpreter writes: <c>#</c>/<c>##</c> headings, <c>- </c>
/// bullets, <c>**bold**</c>, <c>`code`</c>, paragraphs) as an A4 PDF, for the "one click → audit-ready document"
/// download (FUNCTIONAL.md §8.10).
/// <para>
/// Written directly to the PDF format with the standard Helvetica fonts, so there is no third-party dependency or
/// font file to ship. Those fonts cover Western European text (WinAnsi); other characters are written as <c>?</c>.
/// Every page carries the document title, page number and generation time.
/// </para>
/// </summary>
public static class NarrativePdf
{
    private const double PageWidth = 595.28, PageHeight = 841.89, Margin = 56;
    private const double ContentWidth = PageWidth - 2 * Margin;
    private static readonly Encoding WinAnsi = CodePagesEncoding();

    private sealed record Line(string Text, bool Bold, double Size, double Indent, double SpaceBefore);

    public static byte[] Render(string markdown, string title, DateTime generatedAtUtc)
    {
        var lines = Layout(markdown);
        var pages = Paginate(lines);
        var footer = $"{title} · generated by Flowamaz {generatedAtUtc.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)} UTC";
        var streams = pages.Select((page, i) => PageContent(page, footer, i + 1, pages.Count)).ToList();
        return Write(streams, title);
    }

    // ── Layout ─────────────────────────────────────────────────────────────────────

    private static List<Line> Layout(string markdown)
    {
        var result = new List<Line>();
        foreach (var raw in markdown.Replace("\r\n", "\n").Split('\n'))
        {
            var line = raw.TrimEnd();
            if (line.Length == 0) continue;
            if (line.StartsWith("# ", StringComparison.Ordinal))
                Wrap(result, Clean(line[2..]), bold: true, size: 16, indent: 0, spaceBefore: result.Count == 0 ? 0 : 14);
            else if (line.StartsWith("## ", StringComparison.Ordinal))
                Wrap(result, Clean(line[3..]), bold: true, size: 12.5, indent: 0, spaceBefore: 12);
            else if (line.StartsWith("- ", StringComparison.Ordinal))
                Wrap(result, Clean(line[2..]), bold: false, size: 10, indent: 12, spaceBefore: 2, bullet: true);
            else
                Wrap(result, Clean(line), bold: false, size: 10, indent: 0, spaceBefore: 5);
        }
        return result;
    }

    private static string Clean(string s) => s.Replace("**", "").Replace("`", "").Trim();

    private static void Wrap(List<Line> into, string text, bool bold, double size, double indent, double spaceBefore, bool bullet = false)
    {
        var width = ContentWidth - indent - (bullet ? 10 : 0);
        var words = text.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        var current = new StringBuilder();
        var first = true;
        void Flush()
        {
            var prefix = bullet ? (first ? "• " : "  ") : "";
            into.Add(new Line(prefix + current, bold, size, indent, first ? spaceBefore : 0));
            current.Clear();
            first = false;
        }
        foreach (var word in words)
        {
            var candidate = current.Length == 0 ? word : current + " " + word;
            if (current.Length > 0 && TextWidth(candidate, bold, size) > width) Flush();
            // A single word wider than the line (an id, a URL) is split.
            var w = current.Length == 0 ? word : " " + word;
            while (current.Length == 0 && TextWidth(w, bold, size) > width)
            {
                var cut = Math.Max(1, (int)(w.Length * width / TextWidth(w, bold, size)));
                current.Append(w[..cut]);
                Flush();
                w = w[cut..];
            }
            current.Append(w);
        }
        if (current.Length > 0 || first) Flush();
    }

    private static List<List<Line>> Paginate(List<Line> lines)
    {
        var pages = new List<List<Line>> { new() };
        var y = 0.0;
        var usable = PageHeight - 2 * Margin - 24; // room for the footer
        foreach (var line in lines)
        {
            var height = line.SpaceBefore + line.Size * 1.35;
            if (y + height > usable && pages[^1].Count > 0)
            {
                pages.Add([]);
                y = 0;
                height = line.Size * 1.35;
                pages[^1].Add(line with { SpaceBefore = 0 });
            }
            else pages[^1].Add(line);
            y += height;
        }
        return pages;
    }

    private static string PageContent(List<Line> lines, string footer, int page, int pageCount)
    {
        var sb = new StringBuilder();
        var y = PageHeight - Margin;
        foreach (var line in lines)
        {
            y -= line.SpaceBefore + line.Size * 1.35;
            sb.Append(Text(Margin + line.Indent, y, line.Bold ? "F2" : "F1", line.Size, line.Text));
        }
        sb.Append("0.6 g\n");
        sb.Append(Text(Margin, Margin - 20, "F1", 8, footer));
        var pageText = $"Page {page} of {pageCount}";
        sb.Append(Text(PageWidth - Margin - TextWidth(pageText, false, 8), Margin - 20, "F1", 8, pageText));
        return sb.ToString();
    }

    private static string Text(double x, double y, string font, double size, string text) =>
        string.Create(CultureInfo.InvariantCulture, $"BT /{font} {size:0.##} Tf {x:0.##} {y:0.##} Td ({Escape(text)}) Tj ET\n");

    private static string Escape(string text)
    {
        var sb = new StringBuilder(text.Length);
        foreach (var b in WinAnsi.GetBytes(text))
        {
            var c = (char)b;
            if (c is '(' or ')' or '\\') sb.Append('\\').Append(c);
            else if (b < 32 || b > 126) sb.Append('\\').Append(Convert.ToString(b, 8).PadLeft(3, '0'));
            else sb.Append(c);
        }
        return sb.ToString();
    }

    // Helvetica / Helvetica-Bold advance widths (per 1000 em) for ASCII 32–126; others use an average.
    private static readonly short[] Regular =
    [
